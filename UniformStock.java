    public UniformStock(String filter) {
        this();
        this.stockFilter = filter;

        settingFilter = true;
        switch (filter) {
            case "AVAILABLE": cbFilter.setSelectedIndex(1); jLabel9.setText("Showing: Available items only"); break;
            case "LOW":       cbFilter.setSelectedIndex(2); jLabel9.setText("Showing: Low stock items only"); break;
            case "NO":        cbFilter.setSelectedIndex(3); jLabel9.setText("Showing: Out of stock items only"); break;
        }
        settingFilter = false;

        loadStock();
    }

    private String filterClause() {
        switch (stockFilter) {
            case "AVAILABLE": return " WHERE available > 0";
            case "LOW":       return " WHERE available > 0 AND available <= " + LOW_STOCK_LIMIT;
            case "NO":        return " WHERE available <= 0";
            default:          return "";
        }
    }

    private void setupFilter() {
        cbFilter.setModel(new javax.swing.DefaultComboBoxModel<>(new String[] {
            "All Items", "Available", "Low on Stock", "Out of Stock"
        }));
        cbFilter.setFont(new java.awt.Font("Segoe UI Semibold", 0, 12));
        cbFilter.addActionListener(e -> onFilterChosen());
    }

    private void onFilterChosen() {
        if (settingFilter) return;

        switch (cbFilter.getSelectedIndex()) {
            case 1:
                stockFilter = "AVAILABLE";
                jLabel9.setText("Showing: Available items only");
                break;
            case 2:
                stockFilter = "LOW";
                jLabel9.setText("Showing: Low stock items only");
                break;
            case 3:
                stockFilter = "NO";
                jLabel9.setText("Showing: Out of stock items only");
                break;
            default:
                stockFilter = "ALL";
                jLabel9.setText("View and manage uniform stocks and their status.");
        }
        loadStock();
    }
    
