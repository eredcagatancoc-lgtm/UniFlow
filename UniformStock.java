    private void loadStock() {
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
            new String[]{"No.", "Uniform Type", "Size", "Available", "Status"}, 0) {
        @Override
        public boolean isCellEditable(int r, int c) { return false; }
    };

    String sql = "SELECT uniform_type, size, available FROM stock"
       + filterClause() + " ORDER BY id";

    try (java.sql.Connection con = DBConnection.getConnection();
         java.sql.PreparedStatement ps = con.prepareStatement(sql);
         java.sql.ResultSet rs = ps.executeQuery()) {

        int no = 1;
        while (rs.next()) {
            int available = rs.getInt("available");
            String status = available <= 0 ? "Out of Stock"
              : available <= LOW_STOCK_LIMIT ? "Low Stock" : "Available";
            model.addRow(new Object[]{
            no++, rs.getString("uniform_type"), rs.getString("size"),
            available, status
            });
        }
        jTable1.setModel(model);
        jTable1.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);

        javax.swing.table.DefaultTableCellRenderer center = new javax.swing.table.DefaultTableCellRenderer();
        center.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
        javax.swing.table.DefaultTableCellRenderer headerRenderer =
        (javax.swing.table.DefaultTableCellRenderer) jTable1.getTableHeader().getDefaultRenderer();
        headerRenderer.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
        for (int i = 0; i < jTable1.getColumnCount(); i++) {
            jTable1.getColumnModel().getColumn(i).setCellRenderer(center);
        }
        applyStatusColors();
        jTable1.setRowHeight(30);
        jTable1.getColumnModel().getColumn(0).setMaxWidth(60);
        applySearch();

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Could not load stock: " + e.getMessage());
    }
}
    
        private void applyStatusColors() {
        jTable1.getColumnModel().getColumn(4).setCellRenderer(new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable table, Object value,
                    boolean isSelected, boolean hasFocus, int row, int column) {

                java.awt.Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);

                String status = (value == null) ? "" : value.toString();
                setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
                setFont(getFont().deriveFont(java.awt.Font.BOLD));

                if (!isSelected) {
                    setBackground(table.getBackground());
                    if ("Available".equalsIgnoreCase(status)) {
                        setForeground(new java.awt.Color(30, 140, 70));    // green
                    } else if ("Low Stock".equalsIgnoreCase(status)) {
                        setForeground(new java.awt.Color(214, 140, 0));    // amber
                    } else if ("Out of Stock".equalsIgnoreCase(status)) {
                        setForeground(new java.awt.Color(211, 47, 47));    // red
                    } else {
                        setForeground(table.getForeground());
                    }
                }
                return c;
            }
        });
    }
    
    private static final String SEARCH_HINT = "Search by type or size...";

private void setupSearch() {
    txtSearch.setFont(new java.awt.Font("Segoe UI", 0, 14));
    txtSearch.setBackground(java.awt.Color.WHITE);
    txtSearch.setBorder(javax.swing.BorderFactory.createCompoundBorder(
            javax.swing.BorderFactory.createLineBorder(new java.awt.Color(153, 153, 153)),
            javax.swing.BorderFactory.createEmptyBorder(0, 10, 0, 10)));

    txtSearch.setText(SEARCH_HINT);
    txtSearch.setForeground(java.awt.Color.GRAY);
    txtSearch.addFocusListener(new java.awt.event.FocusAdapter() {
        @Override
        public void focusGained(java.awt.event.FocusEvent e) {
            if (txtSearch.getText().equals(SEARCH_HINT)) {
                txtSearch.setText("");
                txtSearch.setForeground(new java.awt.Color(51, 51, 51));
            }
        }
        @Override
        public void focusLost(java.awt.event.FocusEvent e) {
            if (txtSearch.getText().trim().isEmpty()) {
                txtSearch.setText(SEARCH_HINT);
                txtSearch.setForeground(java.awt.Color.GRAY);
            }
        }
    });

    txtSearch.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
        public void insertUpdate(javax.swing.event.DocumentEvent e)  { applySearch(); }
        public void removeUpdate(javax.swing.event.DocumentEvent e)  { applySearch(); }
        public void changedUpdate(javax.swing.event.DocumentEvent e) { applySearch(); }
    });
}

private void applySearch() {
    String typed = txtSearch.getText().trim();
    final String text = typed.equals(SEARCH_HINT) ? "" : typed.toLowerCase();

    javax.swing.table.TableRowSorter<javax.swing.table.TableModel> sorter =
            new javax.swing.table.TableRowSorter<>(jTable1.getModel());
    jTable1.setRowSorter(sorter);

    if (text.isEmpty()) {
        sorter.setRowFilter(null);
        return;
    }

    sorter.setRowFilter(new javax.swing.RowFilter<javax.swing.table.TableModel, Integer>() {
        @Override
        public boolean include(javax.swing.RowFilter.Entry<? extends javax.swing.table.TableModel,
                                                           ? extends Integer> entry) {
            // 1 = Uniform Type, 2 = Size
            String haystack = (entry.getStringValue(1) + " " + entry.getStringValue(2)).toLowerCase();
            for (String word : text.split("\\s+")) {
                if (!haystack.contains(word)) return false;
            }
            return true;
        }
    });
}
    
