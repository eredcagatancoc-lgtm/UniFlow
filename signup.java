    private void signupActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_signupActionPerformed
    
        String uN = username.getText().trim();
        String pW = new String(password.getPassword());

        if (uN.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username is required", "Dialog", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (pW.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Password is required", "Dialog", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try (Connection con = DBConnection.getConnection()) {

            // Is the username already used by a student or the admin?
            String check = "SELECT 1 FROM uniflow_tbl WHERE username = ? "
                         + "UNION SELECT 1 FROM admin_tbl WHERE username = ?";
            try (java.sql.PreparedStatement ps = con.prepareStatement(check)) {
                ps.setString(1, uN);
                ps.setString(2, uN);
                try (ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        JOptionPane.showMessageDialog(this, "That username is already taken.",
                                "Dialog", JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                }
            }

            // Create the account
            try (java.sql.PreparedStatement ps = con.prepareStatement(
                    "INSERT INTO uniflow_tbl (username, password) VALUES (?, ?)")) {
                ps.setString(1, uN);
                ps.setString(2, pW);
                ps.executeUpdate();
            }

            JOptionPane.showMessageDialog(this, "Account created! You can now log in.");
            new login().setVisible(true);
            this.dispose();

        } catch (java.sql.SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_signupActionPerformed

