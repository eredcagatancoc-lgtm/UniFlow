private void setupAdminStats() {
    java.awt.Font f = new java.awt.Font("Segoe UI", 1, 16);
    lblTotal.setFont(f);
    lblApproved.setFont(f);
    lblCompleted.setFont(f);
    lblPending.setFont(f);
    lblCancelled.setFont(f);

    try (java.sql.Connection con = DBConnection.getConnection()) {
        lblTotal.setText("Total Student Signed in: "
                + count(con, "SELECT COUNT(*) FROM uniflow_tbl"));
        lblApproved.setText("Student Approved: " + studentsWith(con, "Approved"));
        lblCompleted.setText("Student Completed: " + studentsWith(con, "Completed"));
        lblPending.setText("Student Pending: " + studentsWith(con, "Pending"));
        lblCancelled.setText("Student Cancelled: " + studentsWith(con, "Cancelled"));

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Could not load student totals: " + e.getMessage());
    }
}

private int studentsWith(java.sql.Connection con, String status) throws java.sql.SQLException {
    try (java.sql.PreparedStatement ps = con.prepareStatement(
            "SELECT COUNT(DISTINCT student_id) FROM requests WHERE status = ?")) {
        ps.setString(1, status);
        try (java.sql.ResultSet rs = ps.executeQuery()) {
            return rs.next() ? rs.getInt(1) : 0;
        }
    }
}

private int count(java.sql.Connection con, String sql) throws java.sql.SQLException {
    try (java.sql.PreparedStatement ps = con.prepareStatement(sql);
         java.sql.ResultSet rs = ps.executeQuery()) {
        return rs.next() ? rs.getInt(1) : 0;
    }
}
