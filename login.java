    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
        String uN = username.getText().trim();
    String pW = new String(password.getPassword());

    if (uN.isEmpty() || pW.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter username and password",
                "Message", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try (Connection conn = DBConnection.getConnection()) {

        // 1. Is this an admin?
        try (PreparedStatement pst = conn.prepareStatement(
                "SELECT admin_id FROM admin_tbl WHERE username = ? AND password = ?")) {
            pst.setString(1, uN);
            pst.setString(2, pW);
            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    UserSession.setUser(rs.getInt("admin_id"), uN, "admin");
                    JOptionPane.showMessageDialog(this, "Login successful! (Admin)");
                    UserSession.newHomePage().setVisible(true);
                    this.dispose();
                    return;
                }
            }
        }

        // 2. Otherwise, a regular account
        try (PreparedStatement pst = conn.prepareStatement(
                "SELECT Users_ID FROM uniflow_tbl WHERE username = ? AND password = ?")) {
            pst.setString(1, uN);
            pst.setString(2, pW);
            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    UserSession.setUser(rs.getInt("Users_ID"), uN, "student");
                    JOptionPane.showMessageDialog(this, "Login successful!");
                    UserSession.newHomePage().setVisible(true);
                    this.dispose();
                    return;
                }
            }
        }

        JOptionPane.showMessageDialog(this, "Invalid username or password",
                "Dialog", JOptionPane.ERROR_MESSAGE);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_loginActionPerformed

