    private void loadRequests() {
        //DefautTableModel organize table rows and columns
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
            //Data Structure Array
            new String[]{"Request No.", "Student ID", "Name", "Year & Section", "Type", "Size", "Date Required", "Status", "Claim Until"}, 0) {
            @Override //Polymorphism Overriding
            public boolean isCellEditable(int row, int col) { return false; }
        };

        boolean admin = UserSession.isAdmin();
        String sql = "SELECT request_no, student_id, name, year_section, type, size, date_required, status, claim_deadline "
           + "FROM requests " + (admin ? "" : "WHERE user_id = ? ") + "ORDER BY request_no ASC";

        //Abstraction
        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

            if (!admin) ps.setInt(1, UserSession.getUserId());

            try (java.sql.ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getInt("request_no"),
                        rs.getString("student_id"),
                        rs.getString("name"),
                        rs.getString("year_section"),
                        rs.getString("type"),
                        rs.getString("size"),
                        rs.getDate("date_required"),
                        rs.getString("status"),
                        "Approved".equalsIgnoreCase(rs.getString("status")) ? rs.getDate("claim_deadline") : null  
                    });
                }
            }
            jTable2.setModel(model);
            jTable2.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);
            jTable2.setRowHeight(28);
            applyStatusColors();
            applyClaimColors();
            setColumnWidths();
            applySearch();

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Could not load requests: " + e.getMessage());
        }
}

