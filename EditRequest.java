    private void btnLoadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadActionPerformed
                String reqText = txtRequestNo.getText().trim();
        if (reqText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Enter the Request No.");
            return;
        }

        int requestNo;
        try {
            requestNo = Integer.parseInt(reqText);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Request No. must be a number.");
            return;
        }

        boolean admin = UserSession.isAdmin();
        String sql = "SELECT student_id, name, year_section, type, size, status FROM requests "
                   + "WHERE request_no = ?" + (admin ? "" : " AND user_id = ?");

        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

            ps.setInt(1, requestNo);
            if (!admin) ps.setInt(2, UserSession.getUserId());

            try (java.sql.ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    setEditEnabled(false);
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "No request found. You can only edit your own requests.");
                    return;
                }
                String st = rs.getString("status");
if (!admin && !"Pending".equalsIgnoreCase(st) && !"Cancelled".equalsIgnoreCase(st)) {
    btnSubmit.setText("Cancelled".equalsIgnoreCase(st) ? "Resubmit Request" : "Save Changes");
    setEditEnabled(false);
    javax.swing.JOptionPane.showMessageDialog(this,
            "Only Pending or Cancelled requests can be edited.");
    return;
}
loadedStatus = st;

                txtStudentId.setText(rs.getString("student_id"));
                txtName.setText(rs.getString("name"));
                txtYearSection.setText(rs.getString("year_section"));
                cbType.setSelectedItem(rs.getString("type"));
                cbSize.setSelectedItem(rs.getString("size"));

                loadedRequestNo = requestNo;
                setEditEnabled(true);
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnLoadActionPerformed

