    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed

        String studentId   = valueOf(txtStudentId, ID_EXAMPLE);
        String name        = txtName.getText().trim();
        String yearSection = InputRules.withDefaultNumber(valueOf(txtYearSection, SECTION_EXAMPLE));
        
        if (studentId.isEmpty() || name.isEmpty() || yearSection.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }
        if (!InputRules.isValidSection(yearSection)) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Year & Section must look like " + InputRules.SECTION_HINT + ".");
            return;
        }
        if (cbType.getSelectedIndex() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a type.");
            return;
        }
        if (cbSize.getSelectedIndex() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a size.");
            return;
        }

        String newType = cbType.getSelectedItem().toString();
String newSize = cbSize.getSelectedItem().toString();
boolean admin = UserSession.isAdmin();

try (java.sql.Connection con = DBConnection.getConnection()) {
    con.setAutoCommit(false);
    try {
        String oldType = null, oldSize = null, status = null;
        try (java.sql.PreparedStatement ps = con.prepareStatement(
                "SELECT type, size, status FROM requests WHERE request_no = ?"
              + (admin ? "" : " AND user_id = ?") + " FOR UPDATE")) {
            ps.setInt(1, loadedRequestNo);
            if (!admin) ps.setInt(2, UserSession.getUserId());
            try (java.sql.ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    oldType = rs.getString("type");
                    oldSize = rs.getString("size");
                    status  = rs.getString("status");
                }
            }
        }

        boolean cancelled = "Cancelled".equalsIgnoreCase(status);
        boolean pending   = "Pending".equalsIgnoreCase(status);
        boolean approved  = "Approved".equalsIgnoreCase(status);

        if (status == null || (!admin && !pending && !cancelled)) {
            con.rollback();
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Could not save. Only Pending or Cancelled requests can be edited.");
            return;
        }

        boolean changedItem = !oldType.equals(newType) || !oldSize.equals(newSize);

        if (cancelled) {
            // A cancelled request holds nothing, so take a new piece.
            try (java.sql.PreparedStatement ps = con.prepareStatement(
                    "UPDATE stock SET available = available - 1 "
                  + "WHERE uniform_type = ? AND size = ? AND available > 0")) {
                ps.setString(1, newType);
                ps.setString(2, newSize);
                if (ps.executeUpdate() == 0) {
                    con.rollback();
                    javax.swing.JOptionPane.showMessageDialog(this,
                            newType + " (" + newSize + ") is out of stock.");
                    return;
                }
            }
        } else if (changedItem && (pending || approved)) {
            // Swap the held piece: take the new one, give back the old one.
            try (java.sql.PreparedStatement ps = con.prepareStatement(
                    "UPDATE stock SET available = available - 1 "
                  + "WHERE uniform_type = ? AND size = ? AND available > 0")) {
                ps.setString(1, newType);
                ps.setString(2, newSize);
                if (ps.executeUpdate() == 0) {
                    con.rollback();
                    javax.swing.JOptionPane.showMessageDialog(this,
                            newType + " (" + newSize + ") is out of stock.");
                    return;
                }
            }
            try (java.sql.PreparedStatement ps = con.prepareStatement(
                    "UPDATE stock SET available = available + 1 "
                  + "WHERE uniform_type = ? AND size = ?")) {
                ps.setString(1, oldType);
                ps.setString(2, oldSize);
                ps.executeUpdate();
            }
        }

        String update = "UPDATE requests SET student_id = ?, name = ?, year_section = ?, type = ?, size = ?"
                      + (cancelled ? ", status = 'Pending', date_required = CURRENT_DATE" : "")
                      + " WHERE request_no = ?";
        try (java.sql.PreparedStatement ps = con.prepareStatement(update)) {
            ps.setString(1, studentId);
            ps.setString(2, name);
            ps.setString(3, yearSection);
            ps.setString(4, newType);
            ps.setString(5, newSize);
            ps.setInt(6, loadedRequestNo);
            ps.executeUpdate();
        }

        con.commit();
        javax.swing.JOptionPane.showMessageDialog(this,
                cancelled ? "Request resubmitted! It is now Pending." : "Request updated!");
        btnSubmit.setText("Save Changes");
        setEditEnabled(false);

    } catch (java.sql.SQLException ex) {
        con.rollback();
        throw ex;
    }
} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnSubmitActionPerformed

