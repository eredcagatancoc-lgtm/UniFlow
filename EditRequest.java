private void placeholder(javax.swing.JTextField field, String example) {
    field.setText(example);
    field.setForeground(java.awt.Color.GRAY);
    field.addFocusListener(new java.awt.event.FocusAdapter() {
        @Override public void focusGained(java.awt.event.FocusEvent e) {
            if (field.getText().equals(example)) {
                field.setText("");
                field.setForeground(java.awt.Color.BLACK);
            }
        }
        @Override public void focusLost(java.awt.event.FocusEvent e) {
            if (field.getText().trim().isEmpty()) {
                field.setText(example);
                field.setForeground(java.awt.Color.GRAY);
            }
        }
    });
}

private String valueOf(javax.swing.JTextField field, String example) {
    String t = field.getText().trim();
    return t.equals(example) ? "" : t;
}
    
