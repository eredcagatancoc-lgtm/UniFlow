    private int count(java.sql.Connection con, String sql, Integer param) throws java.sql.SQLException {
        try (java.sql.PreparedStatement ps = con.prepareStatement(sql)) {
            if (param != null) ps.setInt(1, param);
            try (java.sql.ResultSet rs = ps.executeQuery()) {
                return rs.next() ? rs.getInt(1) : 0;
            }
        }
    }

private void loadDashboard() {
    try (java.sql.Connection con = DBConnection.getConnection()) {

        // Uniforms Request = pending requests (admin: all, student: own)
        if (UserSession.isAdmin()) {
            jLabel10.setText(String.valueOf(
                count(con, "SELECT COUNT(*) FROM requests WHERE status = 'Pending'", null)));
        } else {
            jLabel10.setText(String.valueOf(
                count(con, "SELECT COUNT(*) FROM requests WHERE status = 'Pending' AND user_id = ?",
                      UserSession.getUserId())));
        }

        // Available Stock = total pieces available
        jLabel8.setText(String.valueOf(
            count(con, "SELECT COALESCE(SUM(available), 0) FROM stock", null)));

        // Low on Stock = items with 1..LOW_STOCK_LIMIT left
        jLabel11.setText(String.valueOf(
        count(con, "SELECT COUNT(*) FROM stock WHERE available > 0 AND available <= ?",
          UniformStock.LOW_STOCK_LIMIT)));

        // No Stock = items with 0 left
        jLabel12.setText(String.valueOf(
            count(con, "SELECT COUNT(*) FROM stock WHERE available <= 0", null)));

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Could not load dashboard: " + e.getMessage());
    }
}

